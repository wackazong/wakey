//! not part of this project. Cross-checked against M5Stack's M5GFX
//! (`Panel_ST7123.hpp`): for the ST7123, `0xA3` and `0xE8` take 39 and 14
//! parameters (esp-bsp declares 40 and 15 and reads past its arrays), and
//! SLPOUT/DISPON are sent without parameters.

/// One DCS command: opcode, parameters, delay after sending.
pub(super) struct InitCmd {
    pub cmd: u8,
    pub params: &'static [u8],
    pub delay_ms: u32,
}

impl InitCmd {
    const fn new(cmd: u8, params: &'static [u8], delay_ms: u32) -> Self {
        Self {
            cmd,
            params,
            delay_ms,
        }
    }
}

